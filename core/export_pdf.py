"""Dated PDF log of what was found and done (ReportLab)."""
from __future__ import annotations

import io
from datetime import datetime, timezone

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import LETTER
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import (Image, KeepTogether, PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table,
                                TableStyle)
from xml.sax.saxutils import escape

import config
from core import coverage, rights
from core.models import STATUS_TEXT
from core.pipeline import Batch, thumbnail_jpeg

INK = colors.HexColor("#1F1D17")
MUTED = colors.HexColor("#6B6658")
ACCENT = colors.HexColor("#C99A06")
RULE = colors.HexColor("#D9D2BC")
LABEL_COLORS = {"High": colors.HexColor("#B42318"), "Medium": colors.HexColor("#B54708"),
                "Lower": colors.HexColor("#027A48")}

_ss = getSampleStyleSheet()
H1 = ParagraphStyle("h1", parent=_ss["Title"], alignment=TA_LEFT, fontSize=20, textColor=INK, spaceAfter=4)
H2 = ParagraphStyle("h2", parent=_ss["Heading2"], textColor=INK, spaceBefore=14, spaceAfter=6)
BODY = ParagraphStyle("body", parent=_ss["BodyText"], fontSize=9.5, leading=13, textColor=INK)
SMALL = ParagraphStyle("small", parent=BODY, fontSize=8, leading=10.5, textColor=MUTED)
MONO = ParagraphStyle("mono", parent=BODY, fontName="Courier", fontSize=6.8, leading=8.5, wordWrap="CJK")
CELL = ParagraphStyle("cell", parent=BODY, fontSize=8, leading=10)


def _p(text: str, style=BODY) -> Paragraph:
    return Paragraph(escape(str(text)), style)


def _table(rows, widths, header=True) -> Table:
    t = Table(rows, colWidths=widths, repeatRows=1 if header else 0)
    style = [
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LINEBELOW", (0, 0), (-1, -1), 0.4, RULE),
        ("LEFTPADDING", (0, 0), (-1, -1), 4), ("RIGHTPADDING", (0, 0), (-1, -1), 4),
    ]
    if header:
        style += [("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F6F0DC")),
                  ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, 0), 8)]
    t.setStyle(TableStyle(style))
    return t


def _footer(canvas, doc) -> None:
    canvas.saveState()
    canvas.setFont("Helvetica", 7.5)
    canvas.setFillColor(MUTED)
    canvas.drawString(0.6 * inch, 0.45 * inch,
                      f"Record generated by {config.APP_NAME}. Not a legally certified timestamp.")
    canvas.drawRightString(LETTER[0] - 0.6 * inch, 0.45 * inch, f"Page {doc.page}")
    canvas.restoreState()


def build_pdf(batch: Batch, audit: dict | None = None) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=LETTER, leftMargin=0.6 * inch, rightMargin=0.6 * inch,
                            topMargin=0.6 * inch, bottomMargin=0.7 * inch,
                            title=f"{config.APP_NAME} log", author=batch.artist or config.APP_NAME)
    width = LETTER[0] - 1.2 * inch
    story = []

    # Header
    generated = datetime.now(timezone.utc)
    story += [
        _p(f"{config.APP_NAME}: exposure and action log", H1),
        _p(f"Artist: {batch.artist or 'Not given'} · Website: {batch.website or 'Not given'}"),
        _p(f"Batch started: {batch.created_at} · Log generated: {generated.isoformat(timespec='seconds')} (UTC)"),
        _p(f"App version {config.APP_VERSION}. Scan model: {batch.model_name or 'n/a'}."),
    ]
    if batch.index_info:
        info = batch.index_info
        srcs = "; ".join(f"{s['name']} ({s['count']})" for s in info.get("sources", []))
        story.append(_p(f"Index searched: {info['name']}, {info['size']:,} images, built {info['built_at']}. "
                        f"Sources: {srcs}. {info.get('description', '')}", SMALL))

    # Summary
    pieces = batch.pieces
    labels = [p.label for p in pieces]
    matches = [p.match.label if p.match else "none" for p in pieces]
    summary = [["Pieces", "High", "Medium", "Lower", "Strong matches", "Possible matches", "Tags verified"],
               [len(pieces), labels.count("High"), labels.count("Medium"), labels.count("Lower"),
                matches.count("strong"), matches.count("possible"), sum(p.tag_verified for p in pieces)]]
    story += [_p("Summary", H2), _table(summary, [width / 7] * 7)]

    # Per-piece table
    story.append(_p("Pieces", H2))
    rows = [["", "File", "Hashes (SHA-256)", "Scan", "Score"]]
    for p in pieces:
        thumb = Image(io.BytesIO(thumbnail_jpeg(p.original_bytes, 160)))
        thumb._restrictSize(0.75 * inch, 0.75 * inch)
        hashes = Paragraph(f"original:<br/>{p.sha256_original}<br/>tagged copy:<br/>{p.sha256_tagged or 'n/a'}", MONO)
        m = p.match
        scan = f"{m.label} ({m.top_score:.3f})" if m else "not scanned"
        if m and m.upgraded_by_phash:
            scan += f"; perceptual hash distance {m.phash_distance}"
        score = Paragraph(f'<font color="{LABEL_COLORS.get(p.label, INK).hexval()}"><b>{p.score} {p.label}</b></font>',
                          CELL)
        rows.append([thumb, _p(f"{p.filename}\n{p.width}x{p.height}", CELL), hashes, _p(scan, CELL), score])
    story.append(_table(rows, [0.85 * inch, 1.35 * inch, 3.0 * inch, 1.05 * inch, width - 6.25 * inch]))

    # Per-piece detail: breakdown, next steps, rights
    for p in pieces:
        block = [_p(f"{p.filename}: {p.score}/100 ({p.label})", H2)]
        breakdown = ", ".join(f"{config.SIGNAL_LABELS[k]} +{v}" for k, v in p.breakdown.items()) or "none"
        block.append(_p(f"Score breakdown: {breakdown}.", SMALL))
        steps = [["Next step", "Status"]] + [[_p(f"{s.title}. {s.detail}", CELL), _p(STATUS_TEXT[s.status], CELL)]
                                            for s in p.next_steps]
        block.append(_table(steps, [width - 1.1 * inch, 1.1 * inch]))
        if p.rights_summary:
            r = rights.summarize(p.ai_answers)
            block += [Spacer(1, 4), _p(f"Rights summary: {r['status']}. {p.rights_summary}", CELL),
                      _p(config.NOT_LEGAL_ADVICE, SMALL)]
        story.append(KeepTogether(block))

    # Action history
    story += [PageBreak(), _p("Action history", H2)]
    names = {p.id: p.filename for p in pieces}
    log_rows = [["Time (UTC)", "Piece", "Step", "Status", "Detail"]]
    for a in batch.log.actions:
        log_rows.append([_p(a.ts_utc[:19].replace("T", " "), MONO), _p(names.get(a.piece_id, "batch"), CELL),
                         _p(a.step, CELL), _p(STATUS_TEXT[a.status], CELL), _p(a.detail, MONO)])
    story.append(_table(log_rows, [1.3 * inch, 1.1 * inch, 0.75 * inch, 0.8 * inch, width - 3.95 * inch]))

    # Coverage map snapshot
    cov = coverage.load_coverage()
    table = coverage.as_table()
    story += [_p(f"Coverage map (as of {cov['as_of']})", H2),
              _p("Which protections each AI developer has publicly said it honors. Unknown means we found no "
                 "public statement.", SMALL)]
    short = [t.split(" (")[0] for t in table.columns]
    cov_rows = [["Protection"] + short] + [[_p(idx, CELL)] + list(row) for idx, row in table.iterrows()]
    first = 1.7 * inch
    story.append(_table(cov_rows, [first] + [(width - first) / len(short)] * len(short)))

    # Style audit (optional)
    if audit:
        story += [_p("Style-lift audit", H2),
                  _p(f"Reference artist: {audit['artist']}. {audit.get('caption', '')}", SMALL)]
        a_rows = [["Model", "Style lift", "95% CI", "Styled images"]]
        for m in audit["models"]:
            a_rows.append([_p(m["model"], CELL), f"{m['lift']:+.3f}", f"[{m['ci_low']:+.3f}, {m['ci_high']:+.3f}]",
                           m["n_styled"]])
        story.append(_table(a_rows, [3 * inch, 1.2 * inch, 1.6 * inch, width - 5.8 * inch]))

    # Sources and limits
    story += [_p("Rights summary sources", H2)]
    story += [_p(f"{s['title']}. {s['url']}", SMALL) for s in rights.sources()]
    story += [_p("Limitations", H2)] + [_p(f"• {line}") for line in config.LIMITATIONS]

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buf.getvalue()
